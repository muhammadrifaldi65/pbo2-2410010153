    private void tahunTerbitFieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tahunTerbitFieldKeyTyped
        boolean penuh = tahunTerbitField.getText().length() >= 10
                && tahunTerbitField.getSelectedText() == null;
        if (!Character.isDigit(evt.getKeyChar()) || penuh) {
            evt.consume(); // karakter tidak dimasukkan ke isian
        }
    }//GEN-LAST:event_tahunTerbitFieldKeyTyped

